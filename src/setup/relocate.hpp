#pragma once

// Перенос распакованного дерева на место и приведение имён к нижнему регистру.
//
// Пакеты Microsoft распаковываются в раскладку Windows: «VC», «Windows Kits»,
// «DIA SDK». На файловой системе с учётом регистра обращаться к ним из
// конфигурации и из обёрток неудобно и легко ошибиться, поэтому рядом
// заводятся символьные ссылки с предсказуемыми именами: vc, kits и так далее.
// Сами каталоги не переименовываются: пакеты ссылаются друг на друга по
// исходным именам.

#include <filesystem>
#include <string>

#include "base/error.hpp"

namespace cork::setup {

// Переносит из unpack в dest те части, которые нужны инструментам командной
// строки, сливая с уже существующими каталогами без учёта регистра.
Result<void> relocate_build_tools(const std::filesystem::path &unpack,
                                  const std::filesystem::path &dest);

// Делает так, чтобы проект, привязанный к любому историческому
// PlatformToolset, разрешился в тот единственный компилятор, который
// установлен.
//
// Установлен ли набор инструментов вообще, MSBuild решает проверкой наличия
// каталога Platforms/<arch>/PlatformToolsets/<имя> — обычным обращением к
// диску, на которое не влияет ни одна переменная окружения. Пакет Microsoft
// кладёт туда запись ровно для того поколения, которое скачано, поэтому
// проект, сохранённый под Visual Studio 2019, отвергается сразу, хотя
// собрался бы без единой правки.
//
// Файлы набора не содержат номера версии — они импортируют версионно
// нейтральное, — поэтому символьная ссылка под другим именем это настоящий
// алиас, а не расходящаяся копия.
//
// Возвращает короткое имя настоящего набора, найденного на диске.
Result<std::string> alias_platform_toolsets(const std::filesystem::path &dest);

// Заводит ссылки vc, kits и вложенные tools/msvc. Идемпотентно.
Result<void> create_layout_links(const std::filesystem::path &dest);

// Сливает src в dest: одноимённые каталоги объединяются (сравнение имён без
// учёта регистра — пакеты не выдерживают его единообразно), файлы
// переносятся. Столкновение файла с каталогом — отказ, а не тихая перезапись.
Result<void> merge_trees(const std::filesystem::path &src, const std::filesystem::path &dest);

} // namespace cork::setup
