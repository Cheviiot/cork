#pragma once

// Копирование дерева с попыткой обойтись без копирования данных.
//
// Нужно для префиксов Wine: каждая сборка получает свой, а весит он больше
// полугигабайта. На btrfs и xfs это стоит почти ничего — FICLONE делает
// ссылку на те же экстенты, и настоящая запись происходит только при
// изменении. На ext4 придётся копировать по-настоящему, и знать об этом надо
// заранее, а не обнаружить по забитому диску.
//
// Жёсткие ссылки запрещены здесь категорически, и это не вопрос вкуса. Wine
// перезаписывает встроенные DLL в префиксе на месте (dlls/setupapi/fakedll.c,
// create_dest_file). Жёсткая ссылка означала бы, что запись в префикс одной
// сборки меняет файл в общем runtime или в префиксе соседней сборки. Такая
// порча проявляется не там и не тогда, где сделана.

#include <cstdint>
#include <filesystem>
#include <string>

#include "base/error.hpp"

namespace cork::fs {

enum class CloneMethod {
    // FICLONE: ядро делит экстенты, данные не копируются.
    Reflink,
    // copy_file_range: копирование внутри ядра, без прохода через юзерспейс.
    CopyFileRange,
    // Обычные read/write. Всегда работает, всегда стоит полную цену.
    ReadWrite,
};

struct CloneStats {
    std::uint64_t files = 0;
    std::uint64_t directories = 0;
    std::uint64_t symlinks = 0;
    std::uint64_t bytes = 0;
    // Каким способом скопирован первый файл. Дальше способ не меняется:
    // файловая система одна, и если reflink не вышел на первом файле, он не
    // выйдет и на остальных.
    CloneMethod method = CloneMethod::Reflink;
};

// Копирует дерево from в to. Каталог to создаётся; если он уже существует и не
// пуст — отказ, потому что смешивание двух деревьев даёт результат, который
// потом невозможно объяснить.
//
// Символьные ссылки переносятся ссылками, права и время изменения
// сохраняются: префикс Wine чувствителен и к тому, и к другому.
[[nodiscard]] Result<CloneStats> clone_tree(const std::filesystem::path &from,
                                            const std::filesystem::path &to);

// Поддерживает ли файловая система под path быстрое клонирование. Проверяется
// настоящей попыткой на временном файле, а не по имени файловой системы:
// btrfs без reflink и ext4 с ним одинаково возможны.
[[nodiscard]] bool supports_reflink(const std::filesystem::path &dir);

const char *clone_method_name(CloneMethod);

} // namespace cork::fs
