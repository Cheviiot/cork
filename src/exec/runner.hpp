#pragma once

// Запуск Wine-хостируемого инструмента.
//
// Дерево процессов: обёртка (этот код) -> wine -> cork-helper.exe ->
// настоящий cl.exe. Хелпер нужен потому, что полный код возврата, Job Object
// и настоящая трансляция путей доступны только изнутри Windows-процесса.
//
// Нативная сторона — один цикл poll над потоками вывода, signalfd и timerfd.
// Один цикл, а не поток на каждый конвейер плюс отдельный таймер: так нет
// ни очерёдности между «дождались процесса» и «дочитали вывод», ни риска
// потерять хвост вывода, забрав статус раньше времени.

#include <filesystem>
#include <string>
#include <vector>

#include "base/error.hpp"
#include "setup/config.hpp"

namespace cork::exec {

struct RunOptions {
    // Корень поколения установки; если пусто, ищется от собственного пути.
    std::filesystem::path generation_root;
    // Целевая архитектура; если пусто, берётся из имени каталога обёртки.
    std::string target_arch;
    // Собранная программа вместо инструмента из таблицы. Имя инструмента при
    // этом не смотрится. Нужно, чтобы запустить то, что только что собрали:
    // кросс-компиляция, после которой результат нельзя проверить, проверена
    // наполовину, а весь механизм — сессия, префикс, хелпер, коды возврата —
    // тут ровно тот же самый.
    std::filesystem::path program;
};

// Возвращает код, с которым должен завершиться сам Cork. Отказы среды
// (нет Wine, нет конфигурации, хелпер не отчитался) отличимы от отказа
// инструмента: у них коды вне обычного диапазона.
//
//   124 — превышен CORK_TIMEOUT
//   127 — не удалось запустить инструмент
//   130 — прервано сигналом
//    70 — внутренняя ошибка: хелпер не оставил статуса
int run_tool(std::string_view tool, const std::vector<std::string> &args, const RunOptions &);

// Отображение полного 32-битного кода в код процесса. Вынесено отдельно,
// потому что это правило, а не механика: mt.exe завершается с 0x41020001
// («манифест не изменился»), и CMake ожидает увидеть 0xbb.
int map_exit_code(std::string_view tool, std::uint32_t full_code);

} // namespace cork::exec
